def to_html(value):
    """Eski oddiy matn (\n bilan) -> CKEditor HTML. Allaqachon HTML bo'lsa o'zgarmaydi."""
    value = (value or "").strip()
    if not value or value.startswith("<"):
        return value
    return "".join(f"<p>{escape(part).replace(chr(10), '<br>')}</p>" for part in value.split("\n\n"))


